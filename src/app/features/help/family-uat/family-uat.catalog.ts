export function familyUatAllStepIds(script: FamilyUatRoleScript): string[] {
  return script.blocks.flatMap((b) => b.steps.map((s) => s.id));
}

export function familyUatStepCount(script: FamilyUatRoleScript): number {
  return familyUatAllStepIds(script).length;
}
